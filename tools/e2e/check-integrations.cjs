const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')
;(async () => {
  const login = await (await fetch('http://127.0.0.1:8080/api/auth/login', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: 'demo', password: '123456' }),
  })).json()
  const token = login.data.token
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const out = path.resolve('docs/screenshots')
  fs.mkdirSync(path.join(out, 'desktop'), { recursive: true })
  fs.mkdirSync(path.join(out, 'mobile'), { recursive: true })
  const errors = []
  const desktop = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  await desktop.addInitScript((v) => localStorage.setItem('menu.token', v), token)
  const page = await desktop.newPage()
  page.on('pageerror', (e) => errors.push(String(e)))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
  await page.goto('http://localhost:5173/settings/integrations', { waitUntil: 'networkidle' })
  await page.waitForTimeout(900)
  console.log('TEXT', (await page.locator('body').innerText()).replace(/\s+/g, ' ').slice(0, 220))
  await page.screenshot({ path: path.join(out, 'desktop', 'desktop-integrations.png'), fullPage: true })
  await page.getByRole('button', { name: /连接 B 站/ }).click()
  await page.waitForTimeout(1500)
  const qr = page.locator('img[alt="B站登录二维码"]')
  await qr.waitFor({ state: 'visible', timeout: 10000 })
  const size = await qr.evaluate((img) => ({ w: img.naturalWidth, h: img.naturalHeight, src: img.getAttribute('src')?.slice(0, 30) }))
  console.log('QR', JSON.stringify(size))
  await page.screenshot({ path: path.join(out, 'desktop', 'desktop-integrations-qr.png') })
  await page.getByRole('button', { name: /关闭|取消/ }).first().click().catch(() => {})
  await desktop.close()

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
  await mobile.addInitScript((v) => localStorage.setItem('menu.token', v), token)
  const mp = await mobile.newPage()
  await mp.goto('http://localhost:5173/settings/integrations', { waitUntil: 'networkidle' })
  await mp.waitForTimeout(700)
  const metrics = await mp.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth }))
  console.log('MOBILE', JSON.stringify(metrics))
  await mp.screenshot({ path: path.join(out, 'mobile', 'mobile-integrations.png'), fullPage: true })
  await mobile.close()
  await browser.close()
  console.log('ERRORS', JSON.stringify(errors.filter((x) => !x.includes('favicon'))))
})().catch((e) => { console.error(e); process.exit(1) })
